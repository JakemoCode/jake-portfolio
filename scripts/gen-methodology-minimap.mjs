// Regenerates src/content/methodologyMinimap.ts from the evidence doc behind
// the "How I work with AI" section. The doc lives outside this repo, so the
// line data is committed and this script is only rerun when the doc changes.
//
//   node scripts/gen-methodology-minimap.mjs [path/to/evidence-doc.md]
import { readFileSync, writeFileSync } from "node:fs";

// The default doc and the output resolve from this file, so they work from any
// cwd. A doc path passed as an argument resolves from the cwd.
const src = process.argv[2] ?? new URL("../../docs/how-i-work-with-ai.md", import.meta.url);
const dest = new URL("../src/content/methodologyMinimap.ts", import.meta.url);
const lines = readFileSync(src, "utf8").replace(/\n$/, "").split("\n");

const starts = [];
const lengths = [];
const headingLines = {};

lines.forEach((line, i) => {
  const trimmed = line.trimEnd();
  const start = trimmed.length - trimmed.trimStart().length;
  starts.push(start);
  lengths.push(trimmed.length - start);
  if (trimmed.startsWith("## ")) headingLines[trimmed.slice(3)] = i;
});

const out = `// Generated by scripts/gen-methodology-minimap.mjs. Do not edit by hand.
// One entry per line of the evidence doc: where its text starts and how long
// it runs, in characters. Drawn as the minimap the section distills from.
export const minimapStarts: readonly number[] = ${JSON.stringify(starts)};
export const minimapLengths: readonly number[] = ${JSON.stringify(lengths)};
/** Each "## " heading's text to the line it sits on. */
export const minimapHeadingLines: Readonly<Record<string, number>> = ${JSON.stringify(headingLines, null, 2)};
`;
writeFileSync(dest, out);
console.log(`${lines.length} lines, ${Object.keys(headingLines).length} headings`);
